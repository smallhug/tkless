#!/usr/bin/env node
// Generate the preset overrides in cordis.patch.yml from the DSH installation.
//
// DSH ships its agent presets inside app.asar. This script reads them directly,
// converts each `- insert:` declaration into a patch override, and sets
// `tool-web.config.search = false` so the built-in web_search is never
// registered. The override replaces the complete preset config, so the whole
// plugin list is restated verbatim.
//
// Usage:
//   node scripts/sync-dsh-presets.cjs [--asar <path>] [--check]
//
// --check exits 1 when the committed cordis.patch.yml differs from what this
// DSH installation would generate (for example after a DSH upgrade).

const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const PRESETS = ['standard', 'ptc', 'cordis']
const PATCH_HEADER = [
  '# Generated by scripts/sync-dsh-presets.cjs from the installed',
  '# @deepseek-ai/dsh-web-app presets. Do not edit the preset overrides by hand:',
  '# each one restates the complete preset plugin list for one DSH version.',
  '#',
  '# web_search is removed by `search: false` on tool-web; web_fetch is kept.',
].join('\n')

function fail(message) {
  console.error(`sync-dsh-presets: ${message}`)
  process.exit(1)
}

function parseArgs(argv) {
  const options = { asar: process.env.DSH_ASAR, check: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--check') {
      options.check = true
    } else if (arg === '--asar') {
      options.asar = argv[++index]
    } else if (arg.startsWith('--asar=')) {
      options.asar = arg.slice('--asar='.length)
    } else {
      fail(`unknown argument: ${arg}`)
    }
  }
  return options
}

function defaultAsar() {
  const candidates = [
    process.env.LOCALAPPDATA &&
      path.join(process.env.LOCALAPPDATA, 'Programs', 'DeepSeek Harness', 'resources', 'app.asar'),
    '/Applications/DeepSeek Harness.app/Contents/Resources/app.asar',
    '/opt/DeepSeek Harness/resources/app.asar',
  ].filter(Boolean)
  return candidates.find((candidate) => fs.existsSync(candidate))
}

class Asar {
  constructor(file) {
    this.file = file
    const descriptor = fs.openSync(file, 'r')
    try {
      const head = Buffer.alloc(16)
      fs.readSync(descriptor, head, 0, 16, 0)
      const jsonSize = head.readUInt32LE(12)
      const header = Buffer.alloc(jsonSize)
      fs.readSync(descriptor, header, 0, jsonSize, 16)
      this.tree = JSON.parse(header.toString('utf8'))
      this.dataStart = 16 + jsonSize
    } finally {
      fs.closeSync(descriptor)
    }
  }

  entry(relative) {
    let node = this.tree
    for (const part of relative.split('/')) {
      node = node?.files?.[part]
      if (!node) return undefined
    }
    return node
  }

  read(relative) {
    const entry = this.entry(relative)
    if (!entry || entry.size === undefined || entry.offset === undefined) {
      fail(`cannot find ${relative} in ${this.file}`)
    }
    const offset = Number(entry.offset)
    const size = Number(entry.size)
    if (!Number.isFinite(offset) || !Number.isFinite(size)) {
      fail(`invalid asar entry for ${relative}`)
    }
    const descriptor = fs.openSync(this.file, 'r')
    try {
      const buffer = Buffer.alloc(size)
      fs.readSync(descriptor, buffer, 0, buffer.length, this.dataStart + offset)
      return buffer
    } finally {
      fs.closeSync(descriptor)
    }
  }
}

function dedent(lines, width) {
  const prefix = ' '.repeat(width)
  return lines.map((line) => (line.startsWith(prefix) ? line.slice(width) : line))
}

function injectSearchFalse(lines) {
  const toolWeb = lines.findIndex((line) => /^\s*- id: tool-web\s*$/.test(line))
  if (toolWeb === -1) return lines
  let config = -1
  for (let index = toolWeb + 1; index < lines.length; index += 1) {
    if (/^\s*- id: /.test(lines[index]) && index > toolWeb + 1) break
    if (/^\s*config:\s*$/.test(lines[index])) {
      config = index
      break
    }
  }
  if (config === -1) return lines
  const end = lines.findIndex((line, index) => index > config && /^\s*- id: /.test(line))
  const limit = end === -1 ? lines.length : end
  for (let index = config + 1; index < limit; index += 1) {
    if (/^\s*search:\s*/.test(lines[index])) {
      const indent = /^(\s*)/.exec(lines[index])[1]
      lines[index] = `${indent}search: false`
      return lines
    }
  }
  const fetchIndex = lines.findIndex(
    (line, index) => index > config && index < limit && /^\s*fetch:\s*true\s*$/.test(line),
  )
  if (fetchIndex === -1) return lines
  const indent = /^(\s*)/.exec(lines[fetchIndex])[1]
  lines.splice(fetchIndex + 1, 0, `${indent}search: false`)
  return lines
}

function toOverride(source, id) {
  const lines = source.replace(/\r\n/g, '\n').split('\n')
  const insertIndex = lines.findIndex((line) => /^- insert:\s*$/.test(line))
  if (insertIndex === -1) fail(`preset ${id} has no - insert: header`)
  const idLine = lines.findIndex(
    (line, index) => index > insertIndex && new RegExp(`^\\s+- id: preset-${id}\\s*$`).test(line),
  )
  if (idLine === -1) fail(`preset ${id} has no preset-${id} row`)
  const body = dedent(lines.slice(idLine + 1), 4)
  const withSearch = injectSearchFalse(body)
  return [`- id: preset-${id}`, ...withSearch].join('\n').replace(/\n+$/, '')
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const asarPath = options.asar || defaultAsar()
  if (!asarPath) fail('cannot locate app.asar; pass --asar <path> or set DSH_ASAR')
  if (!fs.existsSync(asarPath)) fail(`app.asar does not exist: ${asarPath}`)

  const asar = new Asar(asarPath)
  let dshVersion = 'unknown'
  try {
    dshVersion = JSON.parse(asar.read('dsh/package.json').toString('utf8')).version
  } catch {
    // keep unknown
  }

  const overrides = []
  const presetHashes = {}
  for (const id of PRESETS) {
    const relative = `dsh/node_modules/@deepseek-ai/dsh-web-app/presets/${id}.patch.yml`
    const source = asar.read(relative)
    presetHashes[id] = crypto.createHash('sha256').update(source).digest('hex')
    overrides.push(toOverride(source.toString('utf8'), id))
  }

  const bridge = [
    '- insert:',
    '    - id: tkless-dsh',
    "      name: './dsh/index.js'",
    '      config:',
    '        autoDownload: true',
    "        protocolVersion: '2026-07-28'",
  ].join('\n')

  const output = `${PATCH_HEADER}\n\n${bridge}\n\n${overrides.join('\n\n')}\n`
  const outPath = path.join(__dirname, '..', 'cordis.patch.yml')
  const pkgPath = path.join(__dirname, '..', 'package.json')

  if (options.check) {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
    if (pkg.engines?.dsh !== dshVersion) {
      console.error(`package.json engines.dsh is ${pkg.engines?.dsh}; this DSH is ${dshVersion}`)
      process.exit(1)
    }
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : ''
    if (current !== output) {
      console.error('cordis.patch.yml is out of date for this DSH installation.')
      const currentLines = current.split('\n')
      const outputLines = output.split('\n')
      for (let index = 0; index < Math.max(currentLines.length, outputLines.length); index += 1) {
        if (currentLines[index] !== outputLines[index]) {
          console.error(`first difference at line ${index + 1}:`)
          console.error(`  committed: ${JSON.stringify(currentLines[index] ?? '<missing>')}`)
          console.error(`  expected:  ${JSON.stringify(outputLines[index] ?? '<missing>')}`)
          break
        }
      }
      process.exit(1)
    }
    console.log(`cordis.patch.yml matches @deepseek-ai/dsh-web-app@${dshVersion}`)
    return
  }

  fs.writeFileSync(outPath, output)
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
  pkg.engines = { ...(pkg.engines ?? {}), dsh: dshVersion }
  fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`)
  fs.writeFileSync(
    path.join(__dirname, '..', 'dsh', 'upstream.json'),
    `${JSON.stringify(
      {
        source: '@deepseek-ai/dsh-web-app',
        dshVersion,
        presets: presetHashes,
      },
      null,
      2,
    )}\n`,
  )
  console.log(`wrote ${outPath} for @deepseek-ai/dsh-web-app@${dshVersion}`)
}

main()
